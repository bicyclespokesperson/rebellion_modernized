void DirectDrawHost::ReportError(HRESULT result, HWND parent)
{
  if (result == 0) {
    return;
  }
  if (reportErrors_ != 1) {
    return;
  }
  const UINT stringId = ErrorStringId(result);
  char caption[0x100]{};
  char text[0x100]{};
  if (directDraw2_) {
    directDraw2_->FlipToGDISurface();
  }
  if (errorModule_) {
    reb::compat::LoadStringA(errorModule_, kCaptionStringId, caption, kStringBufferSize);
    reb::compat::LoadStringA(errorModule_, stringId, text, kStringBufferSize);
    reb::compat::MessageBoxExA(parent, text, caption, kMessageBoxFlags, kEnglishUs);
  }
}
