UINT ErrorStringId(HRESULT result)
{
  int low = 0;
  int high = static_cast<int>(sizeof(kErrorStrings) / sizeof(kErrorStrings[0])) - 1;
  while (low <= high) {
    const int middle = (low + high) / 2;
    const uint32_t candidate = kErrorStrings[middle].result;
    if (candidate == static_cast<uint32_t>(result)) {
      return kErrorStrings[middle].stringId;
    }
    if (candidate < static_cast<uint32_t>(result)) {
      low = middle + 1;
    } else {
      high = middle - 1;
    }
  }
  return kUnknownErrorStringId;
}
