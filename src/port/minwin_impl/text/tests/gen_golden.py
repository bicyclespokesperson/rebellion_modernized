#!/usr/bin/env python3
"""Writes text/text_golden.inc from a Wine reference run (build/minwin_impl/text/real.lines.txt, produced by run_wine_text.sh with
Liberation Sans 2.1.5 standing in for Arial): per game font the text metrics, the extents of four fixed strings and the
word-wrapped rectangle of one of them. Only metrics and measurements of generic ASCII strings are kept, no game text."""
import re
import sys
from pathlib import Path

lines = Path(sys.argv[1]).read_text().splitlines()
out = ["// Generated by tests/gen_golden.py from a Wine run (real gdi32 + Liberation Sans 2.1.5). Do not edit.",
       "// {lfHeight, lfWeight, tmHeight, ascent, descent, internalLeading, externalLeading, aveCharWidth, maxCharWidth, tmWeight,",
       "//  extent(fox), extent(hello), extent(www), extent(rebellion), wrapped-fox width/height at 100 px}"]
fonts: dict[str, dict] = {}
for l in lines:
    m = re.match(r"f(\d+)w(\d+) metrics h=(\d+) asc=(\d+) desc=(\d+) intlead=(\d+) extlead=(\d+) avgw=(\d+) maxw=(\d+) weight=(\d+)", l)
    if m:
        fonts[f"{m[1]}w{m[2]}"] = {"m": [int(x) for x in m.groups()]}
for l in lines:
    m = re.match(r"f(\d+)w(\d+) fixedextent \[(.*)\] (\d+) (\d+)", l)
    if m:
        fonts[f"{m[1]}w{m[2]}"].setdefault("e", []).append(int(m[4]))
    m = re.match(r"f(\d+)w(\d+) fixedwrap \[The quick.*\] (\d+),(\d+) ret=", l)
    if m:
        fonts[f"{m[1]}w{m[2]}"]["w"] = [int(m[3]), int(m[4])]
for key, f in fonts.items():
    v = f["m"] + f["e"] + f["w"]
    out.append("{" + ", ".join(str(x) for x in v) + "},")
Path(sys.argv[2]).write_text("\n".join(out) + "\n")
print(len(fonts), "fonts")
