#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.10"
# ///
"""Generate the import-address-table slots of the native minwin implementation (i686 Windows only).

The game objects are compiled with `__declspec(dllimport)` declarations (REB_MINWIN), so every call goes through a
`__imp__Name@N` slot. With the real import libraries the linker takes the slots from user32.lib & co.; with
REB_MINWIN_IMPL the implementation defines them itself, pointing at its own functions (the same trick as
src/standalone/determinism.cpp). The set of functions comes from the minwin headers, so a function that is declared but not
implemented shows up as an unresolved `_Name@N` at link time.

  gen_minwin_imports.py --out gen/minwin_imports.cpp --header src/port/minwin/user32.h [--header winmm.h:timeKillEvent,...]
                        [--extra wvsprintfA:12:"int __stdcall wvsprintfA(char*, const char*, va_list)"]
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

DECLARATION = re.compile(r"MINWIN_IMPORT\s+(?:\[\[noreturn\]\]\s+)?(?P<ret>[\w\s\*]+?)\s+REB_(?P<conv>STDCALL|CDECL)\s+(?P<name>\w+)\((?P<args>[^;]*)\);")
BY_VALUE_SIZES = {"POINT": 8, "SIZE": 8}


def parameter_bytes(arguments: str) -> int | None:
    arguments = arguments.strip()
    if arguments in ("", "void"):
        return 0
    total = 0
    for parameter in arguments.split(","):
        parameter = parameter.strip()
        if parameter == "...":
            return None
        pointer = "*" in parameter
        words = parameter.replace("*", " ").split()
        base = [w for w in words if w not in ("const", "struct")]
        total += 4 if pointer or len(base) < 2 else BY_VALUE_SIZES.get(base[0], 4)
        if not pointer and len(base) >= 2 and base[0] in ("double", "LONGLONG", "ULONGLONG", "__int64"):
            total += 4
    return total


def declarations(header: Path, only: set[str] | None) -> list[tuple[str, str, int | None]]:
    found = []
    for match in DECLARATION.finditer(header.read_text()):
        name = match["name"]
        if only is not None and name not in only:
            continue
        found.append((name, match["conv"], parameter_bytes(match["args"])))
    return found


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--header", action="append", default=[], help="path[:name,name,...]")
    parser.add_argument("--extra", action="append", default=[], help="name:bytes:prototype (a function the headers do not declare)")
    args = parser.parse_args()

    lines = [
        "// Generated by tools/gen_minwin_imports.py. Do not edit.",
        "#define MINWIN_IMPLEMENTATION 1",
        "#include <stdarg.h>",
        '#include "port/minwin/minwin.h"',
        "",
        "template <class T> struct StackBytes;",
        "template <class R, class... A> struct StackBytes<R(__stdcall*)(A...)> {",
        "    static constexpr unsigned value = (0u + ... + static_cast<unsigned>((sizeof(A) + 3) & ~3u));",
        "};",
        "",
        "#define SLOT(symbol, function) \\",
        '    extern "C" void* const slot_##function __asm__(symbol); \\',
        '    extern "C" void* const slot_##function = reinterpret_cast<void*>(&function)',
        "",
    ]
    for entry in args.header:
        path, _, names = entry.partition(":")
        only = set(names.split(",")) if names else None
        lines.append(f"// {Path(path).name}")
        for name, conv, size in declarations(Path(path), only):
            if conv == "CDECL" or size is None:
                lines.append(f'SLOT("__imp__{name}", {name});')
            else:
                lines.append(f"static_assert(StackBytes<decltype(&{name})>::value == {size}, \"{name}: stack size\");")
                lines.append(f'SLOT("__imp__{name}@{size}", {name});')
    for entry in args.extra:
        name, size, prototype = entry.split(":", 2)
        lines.append(f'extern "C" {prototype};')
        lines.append(f'SLOT("__imp__{name}@{size}", {name});')
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
